def pick(options, key):
    return options[zlib.crc32(key.encode("utf-8")) % len(options)]


def fit(slots, key):
    """เลือกชุดข้อความที่ความยาวอยู่ในช่วง 150-155 ตัวอักษร (เลือกแบบคงที่ตาม key)"""
    valid = []
    for combo in itertools.product(*slots):
        text = " ".join(p for p in combo if p).replace("  ", " ").strip()
        if MIN_D <= len(text) <= MAX_D:
            valid.append(text)
    if not valid:
        ls = [len(" ".join(p for p in c if p)) for c in itertools.product(*slots)]
        raise SystemExit(f"ไม่พบ description ที่ยาว {MIN_D}-{MAX_D} สำหรับ: {key} (ช่วงที่เป็นไปได้ {min(ls)}-{max(ls)})")
    return pick(valid, key)


def tool_desc(path, h1, topic, hub=False):
    s1s, s2s = POOLS["qr" if path.startswith("/generator/") else topic]
    s1 = list(HUB_S1) if hub else s1s
    left = " " if re.match(r"[A-Za-z0-9(]", h1) else ""
    right = " " if re.search(r"[A-Za-z0-9)]$", h1) else ""
    s1 = [re.sub(r"\s+", " ", s.replace("{h1}", f"{left}{h1}{right}")).strip() for s in s1]
    s2x = [a + b for a in s2s for b in EXTRA]
    best = None
    for pre in PREFIX:
        for a in s1:
            for b in s2x:
                for m in MID:
                    for t in TAILS:
                        text = f"{pre}{a} {b} {m} {t}".replace("  ", " ")
                        if MIN_D <= len(text) <= MAX_D and text.count("ThaiApp") <= 1:
                            best = best or []
                            best.append(text)
    if not best:
        raise SystemExit(f"ไม่พบ description ที่เหมาะสมสำหรับ {path} ({h1})")
    return pick(best, path)


def make_title(h1):
    for suffix in (" ออนไลน์ ฟรี | ThaiApp", " ฟรี | ThaiApp", " | ThaiApp"):
        if "ออนไลน์" in h1 and "ออนไลน์" in suffix:
            continue
        t = h1 + suffix
        if len(t) <= 60:
            return t
    return h1 + " | ThaiApp"


def write_md(rel, front, body=""):
    p = CONTENT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    fm = yaml.safe_dump(front, allow_unicode=True, sort_keys=False, width=10000, default_flow_style=False)
    p.write_text(f"---\n{fm}---\n{body}", encoding="utf-8")


